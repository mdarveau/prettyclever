/**
 * TD(λ) value network "bonus": v1's features plus an explicit bonus-economy
 * block — the "reward chasing" hypothesis.
 *
 * v1's encoding already carries group completion fractions, but the net must
 * derive the cascade structure itself: which bonus a group grants, how close
 * each printed bonus is to firing, and how productive the bonus engine has
 * been so far. This variant spells those out so they are linearly visible:
 *
 *  - 2: lifetime action-bar unlocks (reroll, +1), /7 — bonus production to
 *    date, invisible in v1 which only sees the *unspent* counters.
 *  - 1: completed bonus-carrying groups, /12.
 *  - 8: "one-away" counts per bonus kind — groups exactly one cell from
 *    firing, the cascade trigger signal (capped at 2, /2). Kind channels:
 *    reroll, +1, fox, X-yellow, X-blue, X-green, write-orange, write-purple.
 *  - 8: write-track "pull" per bonus kind — Σ 1/(1+d) over bonus-carrying
 *    slots at distance d from each track's next fill (capped at 1).
 *
 * 19 extra features, 182 total. Everything else (net shape, afterstate-argmax
 * policy, terminal handling) mirrors v1; MLP code is imported unchanged.
 * Weights live in tdnet-bonus-weights.ts (generated by the parallel trainer
 * with --features v1bonus).
 */
